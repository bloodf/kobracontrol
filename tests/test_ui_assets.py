"""Built wheel ships the compiled Vue page and its icons, sanitized, with no unresolved placeholders."""

import hashlib
import json
import re
import sys
import tempfile
import unittest
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
import build  # noqa: E402

UI = ROOT / "src" / "kobracontrol" / "ui"
MAX_BUILT_BYTES = 400_000   # the wheel measures ~240 kB


class UiAssets(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.artifact = build.build(out_dir=Path(tempfile.mkdtemp()))
        with zipfile.ZipFile(cls.artifact) as z:
            cls.text = z.read("kobracontrol/_assets.py").decode("utf-8")

    def page_icons(self):
        html = build.page_html("app.html")
        match = re.search(r'<script type="application/json" id="kobra-icons">(\{.*?\})</script>', html, re.S)
        self.assertIsNotNone(match)
        return html, json.loads(match.group(1))

    def test_every_referenced_icon_is_inlined(self):
        source = (UI / "app.html").read_text("utf-8")
        html, icons = self.page_icons()
        used = set(re.findall(r"\b(?:icon|spot)/[a-z0-9-]+", source))
        self.assertTrue(used)
        self.assertEqual(used - set(icons), set())
        self.assertNotIn("__ICONS__", html)
        self.assertIn(repr(html), self.text)   # the wheel carries exactly this page

    def test_no_icon_is_shipped_unused(self):
        """Icons the page no longer references are deleted, not carried along."""
        source = (UI / "app.html").read_text("utf-8")
        used = set(re.findall(r"\b(?:icon|spot)/[a-z0-9-]+", source))
        self.assertEqual(set(build.all_icons()) - used, set())

    def test_committed_page_is_the_recorded_vue_build(self):
        """src/kobracontrol/ui/app.html is generated by `npm run build` in ui/; a hand edit or a stale build fails here."""
        info = json.loads((ROOT / "ui" / "build.json").read_text("utf-8"))
        data = (UI / "app.html").read_bytes()
        self.assertEqual(hashlib.sha256(data).hexdigest(), info["sha256"])
        html = data.decode("utf-8")
        self.assertEqual(html.count("__BOOT__"), 1)
        self.assertEqual(html.count("__ICONS__"), 1)
        self.assertIn('id="kobra-boot"', html)
        self.assertIn('id="kobra-icons"', html)
        self.assertNotIn("u1-boot", html)
        self.assertNotRegex(html, r"<script[^>]+src=|<link[^>]+href=\"https?:|@import\s*(?:url\(|['\"])|url\(https?:")
        self.assertNotRegex(html, r"\bnew Function\b|\beval\(")
        self.assertIn("__VUE_OPTIONS_API__", (ROOT / "ui" / "vite.config.ts").read_text("utf-8"))

    def test_page_has_no_u1_leftovers(self):
        html = (UI / "app.html").read_text("utf-8")
        self.assertNotRegex(html, r"U1 Control|u1control|Snapmaker|toolhead/t\d")
        self.assertFalse((ROOT / "ui" / "src" / "setup").exists(), "the print setup pop-up belongs to the U1")

    def test_app_uses_expected_icons(self):
        names = set(re.findall(r"\bicon/([a-z0-9-]+)", (UI / "app.html").read_text("utf-8")))
        for n in ("dashboard", "files", "settings", "pause", "resume", "cancel", "chamber-light", "load-filament", "unload-filament",
                  "ace", "dry", "home", "move", "certificate", "delete", "print-setup"):
            self.assertIn(n, names)
        spots = set(re.findall(r"\bspot/([a-z0-9-]+)", (UI / "app.html").read_text("utf-8")))
        self.assertEqual(spots, {"camera-off", "no-files", "not-connected", "spooler-suggestion"})

    def test_no_unresolved_placeholders(self):
        self.assertIsNone(re.search(r"APP_HTML = '[^\n]*__ICONS__", self.text))
        self.assertNotIn("__ICONS__", build.page_html("app.html"))
        self.assertIn("__BOOT__", build.page_html("app.html"))   # filled per page by plugin.page_html

    def test_inlined_svgs_are_clean(self):
        icons = build.all_icons()
        self.assertGreaterEqual(len(icons), 24 + 4)
        for key, svg in icons.items():
            self.assertTrue(svg.startswith("<svg"), key)
            self.assertNotRegex(svg, r"(?i)<script|\bon\w+\s*=|<\?xml|<!--", key)

    def test_build_rejects_scripted_svg(self):
        with self.assertRaises(SystemExit):
            build.clean_svg('<svg onload="x()"></svg>', "bad")
        with self.assertRaises(SystemExit):
            build.clean_svg("<svg><script>1</script></svg>", "bad")

    def test_built_size_reasonable(self):
        size = self.artifact.stat().st_size
        print("built size: %d bytes" % size)
        self.assertLess(size, MAX_BUILT_BYTES)


if __name__ == "__main__":
    unittest.main()
