"""Built wheel ships the compiled Vue page (icons from the shared foundation) and the tab icon, with no unresolved placeholders."""

import hashlib
import json
import re
import sys
import tempfile
import unittest
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
import build  # noqa: E402

UI = ROOT / "src" / "kobracontrol" / "ui"
MAX_BUILT_BYTES = 675_000   # the wheel measures ~650 kB: six languages, the Kobra X photo, the photo spool layers (foundation 4.1.0+), the built-in camera player and the upload bridge


class UiAssets(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.artifact = build.build(out_dir=Path(tempfile.mkdtemp()))
        with zipfile.ZipFile(cls.artifact) as z:
            cls.text = z.read("kobracontrol/_assets.py").decode("utf-8")

    def test_page_ships_as_built(self):
        """Icons come from the shared foundation, compiled into the page: nothing is injected at build time."""
        html = build.page_html("app.html")
        self.assertEqual(html, (UI / "app.html").read_text("utf-8"))
        self.assertNotIn("__ICONS__", html)
        self.assertNotIn('id="kobra-icons"', html)
        self.assertIn(repr(html), self.text)   # the wheel carries exactly this page

    def test_committed_page_is_the_recorded_vue_build(self):
        """src/kobracontrol/ui/app.html is generated by `npm run build` in ui/; a hand edit or a stale build fails here."""
        info = json.loads((ROOT / "ui" / "build.json").read_text("utf-8"))
        data = (UI / "app.html").read_bytes()
        self.assertEqual(hashlib.sha256(data).hexdigest(), info["sha256"])
        html = data.decode("utf-8")
        self.assertEqual(html.count("__BOOT__"), 1)
        self.assertEqual(html.count("__ICONS__"), 0)
        self.assertIn('id="kobra-boot"', html)
        self.assertNotIn("u1-boot", html)
        self.assertNotRegex(html, r"<script[^>]+src=|<link[^>]+href=\"https?:|@import\s*(?:url\(|['\"])|url\(https?:")
        self.assertNotRegex(html, r"\bnew Function\b|\beval\(")
        self.assertIn("__VUE_OPTIONS_API__", (ROOT / "ui" / "vite.config.ts").read_text("utf-8"))

    def test_page_has_no_u1_leftovers(self):
        html = (UI / "app.html").read_text("utf-8")
        self.assertNotRegex(html, r"U1 Control|u1control|Snapmaker|toolhead/t\d")
        self.assertFalse((ROOT / "ui" / "src" / "setup").exists(), "the print setup pop-up belongs to the U1")

    def test_no_local_icon_files_left(self):
        """The old per-plugin SVG icons and spot pictures were replaced by the foundation's set; only the tab icon stays."""
        self.assertFalse((UI / "icons").exists())
        self.assertEqual(sorted(p.name for p in UI.glob("spot-*.svg")), [])
        self.assertNotRegex((UI / "app.html").read_text("utf-8"), r"\b(?:icon|spot)/(?:chamber-light|load-filament|camera-off|not-connected)\b")
        self.assertFalse((ROOT / "ui" / "src" / "assets" / "spool").exists(), "the spool is drawn (OuiSpool), not rendered pictures")

    def test_no_unresolved_placeholders(self):
        self.assertIsNone(re.search(r"APP_HTML = '[^\n]*__ICONS__", self.text))
        self.assertNotIn("__ICONS__", build.page_html("app.html"))
        self.assertIn("__BOOT__", build.page_html("app.html"))   # filled per page by plugin.page_html

    def test_tab_icon_is_not_scriptable(self):
        self.assertNotRegex((UI / "icon.svg").read_text("utf-8"), r"(?i)<script|\bon\w+\s*=|javascript:")

    def test_built_size_reasonable(self):
        size = self.artifact.stat().st_size
        print("built size: %d bytes" % size)
        self.assertLess(size, MAX_BUILT_BYTES)


if __name__ == "__main__":
    unittest.main()
