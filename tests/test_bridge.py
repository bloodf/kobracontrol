KEY = "k" * 32
BOUNDARY = "------------------------orcaslicer0123"
GCODE = b"; generated by OrcaSlicer\nG90\nM83\nG1 X10 Y10\n" * 100


def orca_body(data=GCODE, filename="cube.gcode", start=False, plate="1"):
    """The multipart body OrcaSlicer's Http::form_add / form_add_file (libcurl) send."""
    parts = [("print", "true" if start else "false"), ("path", "")] + ([("plateindex", plate)] if plate else [])
    out = b""
    for name, value in parts:
        out += ('--%s\r\nContent-Disposition: form-data; name="%s"\r\n\r\n%s\r\n' % (BOUNDARY, name, value)).encode()
    out += ('--%s\r\nContent-Disposition: form-data; name="file"; filename="%s"\r\nContent-Type: application/octet-stream'
            '\r\n\r\n' % (BOUNDARY, filename)).encode() + data + ("\r\n--%s--\r\n" % BOUNDARY).encode()
    return out


class Server(unittest.TestCase):
    def setUp(self):
        self.work = tempfile.mkdtemp()
        self.calls = []
        self.answer = {"name": "cube.gcode"}
        self.bridge = bridge.Bridge(0, lambda: KEY, self.on_upload, self.work, log=lambda m: None).start()
        self.addCleanup(self.bridge.stop)
        self.port = self.bridge.port

    def on_upload(self, path, filename, plate, start):
        with open(path, "rb") as f:
            self.calls.append((f.read(), filename, plate, start))
        if isinstance(self.answer, Exception):
            raise self.answer
        return self.answer

    def request(self, method, path, body=None, key=KEY, host=None, headers=None):
        conn = http.client.HTTPConnection("127.0.0.1", self.port, timeout=10)
        h = {"Host": host or "127.0.0.1:%d" % self.port, **({"X-Api-Key": key} if key is not None else {})}
        if body is not None:
            h["Content-Type"] = "multipart/form-data; boundary=%s" % BOUNDARY
        h.update(headers or {})
        conn.request(method, path, body=body, headers=h)
        resp = conn.getresponse()
        data = resp.read()
        conn.close()
        return resp.status, json.loads(data or b"{}"), resp

    def test_bound_to_loopback_only(self):
        self.assertEqual(self.bridge.server.server_address[0], "127.0.0.1")
        self.assertEqual(bridge.HOST, "127.0.0.1")

    def test_version_as_orcaslicer_checks_it(self):
        status, data, _ = self.request("GET", "/api/version")
        self.assertEqual(status, 200)
        self.assertIn("api", data)                       # OctoPrint::test: "api" must be there
        self.assertTrue(data["text"].startswith("OctoPrint"))   # validate_version_text

    def test_upload_only(self):
        status, data, resp = self.request("POST", "/api/files/local", orca_body(plate="2"))
        self.assertEqual(status, 201)
        self.assertTrue(data["done"])
        self.assertEqual(data["files"]["local"]["name"], "cube.gcode")
        self.assertEqual(self.calls, [(GCODE, "cube.gcode", 2, False)])
        self.assertIsNone(resp.getheader("Access-Control-Allow-Origin"))
        self.assertEqual(os.listdir(self.work), [])   # the received copy is removed

    def test_upload_and_print_flag(self):
        self.request("POST", "/api/files/local", orca_body(start=True, plate=""))
        self.assertEqual(self.calls[0][2:], (1, True))

    def test_windows_path_in_filename(self):
        self.request("POST", "/api/files/local", orca_body(filename="C:\\temp\\part.gcode"))
        self.assertEqual(self.calls[0][1], "part.gcode")

    def test_body_containing_boundary_like_bytes(self):
        data = b"G1 X1\r\n--not-the-boundary\r\n" + b"\r\n-" * 70000 + b"end\n"
        self.assertEqual(self.request("POST", "/api/files/local", orca_body(data))[0], 201)
        self.assertEqual(self.calls[0][0], data)

    def test_key_required(self):
        for key in (None, "", "wrong"):
            status, data, _ = self.request("GET", "/api/version", key=key)
            self.assertEqual(status, 403, key)
            self.assertIn("API key", data["error"])
        status, _, _ = self.request("POST", "/api/files/local", orca_body(), key="wrong")
        self.assertEqual(status, 403)
        self.assertEqual(self.calls, [])

    def test_wrong_keys_lock_out(self):
        for _ in range(bridge.WRONG_KEYS_PER_MINUTE):
            self.request("GET", "/api/version", key="wrong")
        self.assertEqual(self.request("GET", "/api/version")[0], 429)   # even the right key, for a minute

    def test_request_budget(self):
        with mock.patch.object(bridge, "REQUESTS_PER_MINUTE", 3):
            statuses = [self.request("GET", "/api/version")[0] for _ in range(4)]
        self.assertEqual(statuses, [200, 200, 200, 429])

    def test_foreign_host_header_refused(self):   # DNS rebinding: a web page's name resolving to 127.0.0.1
        status, _, _ = self.request("GET", "/api/version", host="evil.example:%d" % self.port)
        self.assertEqual(status, 403)
        self.assertEqual(self.request("GET", "/api/version", host="localhost:%d" % self.port)[0], 200)

    def test_browser_requests_refused(self):   # a web page can POST to 127.0.0.1 without a preflight
        for header in ({"Origin": "https://evil.example"}, {"Sec-Fetch-Site": "cross-site"}):
            status, data, _ = self.request("POST", "/api/files/local", orca_body(), headers=header)
            self.assertEqual(status, 403, header)
        self.assertEqual(self.calls, [])
        self.assertEqual(self.request("GET", "/api/version")[0], 200)   # and they did not lock OrcaSlicer out

    def test_too_many_parts(self):
        part = '--%s\r\nContent-Disposition: form-data; name="x"\r\n\r\n1\r\n' % BOUNDARY
        body = (part * (bridge.PARTS_MAX + 1)).encode() + orca_body()
        self.assertEqual(self.request("POST", "/api/files/local", body)[0], 400)
        self.assertEqual(self.calls, [])

    def test_size_limit(self):
        with mock.patch.object(bridge, "UPLOAD_MAX", 1000):
            status, data, _ = self.request("POST", "/api/files/local", orca_body(b"x" * 5000))
        self.assertEqual(status, 413)
        self.assertEqual(self.calls, [])
        self.assertEqual(os.listdir(self.work), [])

    def test_malformed_uploads(self):
        status, _, _ = self.request("POST", "/api/files/local", b"junk", headers={"Content-Type": "text/plain"})
        self.assertEqual(status, 415)
        status, _, _ = self.request("POST", "/api/files/local", orca_body()[:-200])
        self.assertEqual(status, 400)
        no_file = ('--%s\r\nContent-Disposition: form-data; name="print"\r\n\r\ntrue\r\n--%s--\r\n' % (BOUNDARY, BOUNDARY)).encode()
        self.assertEqual(self.request("POST", "/api/files/local", no_file)[0], 400)
        self.assertEqual(self.calls, [])

    def test_refusal_reaches_orcaslicer(self):
        self.answer = bridge.Refused(409, "the printer is printing; nothing was sent")
        status, data, _ = self.request("POST", "/api/files/local", orca_body(start=True))
        self.assertEqual((status, data["error"]), (409, "the printer is printing; nothing was sent"))

    def test_unknown_paths(self):
        self.assertEqual(self.request("GET", "/api/files")[0], 404)
        self.assertEqual(self.request("POST", "/api/printer/command", orca_body())[0], 404)

    def test_stop_frees_the_port(self):
        self.bridge.stop()
        with self.assertRaises(OSError):
            socket.create_connection(("127.0.0.1", self.port), timeout=1).close()


class Key(unittest.TestCase):
    def test_saved_owner_only_and_kept(self):
        folder = tempfile.mkdtemp()
        key = bridge.key_for(folder)
        self.assertGreaterEqual(len(key), 20)
        self.assertEqual(bridge.key_for(folder), key)
        if os.name == "posix":
            self.assertEqual(stat.S_IMODE(os.stat(os.path.join(folder, bridge.KEY_FILE)).st_mode), 0o600)
        self.assertNotEqual(bridge.write_key(folder, bridge.new_key()), key)

    def test_not_in_settings(self):
        self.assertFalse(any("key" in k for k in settings.DEFAULTS))
        self.assertFalse(settings.DEFAULTS["bridge_enabled"])
        store = settings.Store()
        self.assertEqual(store.update({"bridge_port": 80})["bridge_port"], 8765)
        self.assertEqual(store.update({"bridge_port": 9000})["bridge_port"], 9000)


class PrintFlow(Base):
    """bridge_upload against FakeKobra: the file goes to the printer; a print waits for Start in the tab."""
    TASK = {"auto_leveling": True, "vibration_compensation": False, "flow_calibration": False, "timelapse": False}

    def setUp(self):
        super().setUp()
        self.fake.print_start = "ok"
        self.fake.reply("file", "listLocal", {"records": [{"filename": "cube.gcode", "size": len(GCODE), "timestamp": 1}]},
                        code=200)   # the printer's list, as after the upload
        self.path = os.path.join(self.tmp, "up.part")
        with open(self.path, "wb") as f:
            f.write(GCODE)

    def upload(self, start):
        return self.svc.bridge_upload(self.path, "cube.gcode", 1, start, self.TASK)

    def test_upload_only_starts_nothing(self):
        self.assertEqual(self.upload(False), {"name": "cube.gcode"})
        self.assertEqual(self.fake.uploads[0]["data"], GCODE)
        self.assertIsNone(self.svc.bridge_pending_for(self.fake.host))
        time.sleep(0.2)
        self.assertFalse(self.sent("print", "start"))

    def test_print_waits_for_start(self):
        answer = self.upload(True)
        self.assertTrue(answer["pending"])
        time.sleep(0.2)
        self.assertFalse(self.sent("print", "start"))   # nothing starts without the user
        pending = self.svc.bridge_pending_for(self.fake.host)
        self.assertEqual(pending["name"], "cube.gcode")
        self.assertTrue(any(m.get("type") == "notice" for m in self.published))
        self.assertEqual(self.run_cmd("bridge_start", id="nope")["error"], "that print request is no longer waiting; nothing was started")
        self.assertEqual(self.run_cmd("bridge_start", id=pending["id"])["result"], {"started": "cube.gcode"})
        start = wait(lambda: self.sent("print", "start"))[0]["data"]
        self.assertEqual(start["task_settings"]["auto_leveling"], 1)
        self.assertIsNone(self.svc.bridge_pending_for(self.fake.host))

    def test_cancel_forgets_the_print(self):
        self.upload(True)
        pending = self.svc.bridge_pending_for(self.fake.host)
        self.assertEqual(self.run_cmd("bridge_cancel", id=pending["id"])["result"], {"cancelled": True})
        self.assertIsNone(self.svc.bridge_pending_for(self.fake.host))
        self.assertIn("error", self.run_cmd("bridge_start", id=pending["id"]))
        time.sleep(0.2)
        self.assertFalse(self.sent("print", "start"))

    def test_pending_expires(self):
        self.upload(True)
        with mock.patch.object(jobs.time, "time", return_value=time.time() + jobs.PENDING_TTL + 1):
            self.assertIsNone(self.svc.bridge_pending_for(self.fake.host))

    def test_shown_in_status(self):
        self.upload(True)
        self.svc.touch()
        status = wait(lambda: next((m for m in self.published if m.get("type") == "status"
                                    and m["data"].get("bridge_pending")), None))
        self.assertEqual(status["data"]["bridge_pending"]["name"], "cube.gcode")

    def test_print_refused_while_printing(self):
        self.set_state("printing")
        with self.assertRaises(bridge.Refused) as e:
            self.upload(True)
        self.assertEqual(e.exception.status, 409)
        self.assertIn("printing", str(e.exception))
        self.assertEqual(self.fake.uploads, [])
        self.assertIsNone(self.svc.bridge_pending_for(self.fake.host))

    def test_start_refused_once_printing(self):
        self.upload(True)
        pending = self.svc.bridge_pending_for(self.fake.host)
        self.set_state("printing")
        self.assertIn("printing", self.run_cmd("bridge_start", id=pending["id"])["error"])
        self.assertFalse(self.sent("print", "start"))

    def test_file_being_printed_is_not_overwritten(self):
        self.set_state("printing")   # FakeKobra's job is a.gcode
        with self.assertRaises(bridge.Refused) as e:
            self.svc.bridge_upload(self.path, "a.gcode", 1, False, self.TASK)
        self.assertEqual(e.exception.status, 409)
        self.assertEqual(self.fake.uploads, [])
        self.assertEqual(self.upload(False), {"name": "cube.gcode"})   # another file may go up meanwhile

    def test_same_name_upload_drops_the_waiting_print(self):
        self.upload(True)
        self.upload(False)
        self.assertIsNone(self.svc.bridge_pending_for(self.fake.host))

    def test_send_of_the_same_name_drops_the_waiting_print(self):
        self.upload(True)
        self.svc.send_file(self.fake.host, self.path, "cube")   # OrcaSlicer's Send, not the bridge
        self.assertIsNone(self.svc.bridge_pending_for(self.fake.host))

    def test_start_refused_when_the_file_changed_on_the_printer(self):
        self.upload(True)
        pending = self.svc.bridge_pending_for(self.fake.host)
        self.fake.reply("file", "listLocal", {"records": [{"filename": "cube.gcode", "size": 7, "timestamp": 2}]},
                        code=200)   # replaced by someone else meanwhile
        self.assertIn("not the file OrcaSlicer sent", self.run_cmd("bridge_start", id=pending["id"])["error"])
        time.sleep(0.2)
        self.assertFalse(self.sent("print", "start"))
        self.assertIsNone(self.svc.bridge_pending_for(self.fake.host))

    def test_no_printer_selected(self):
        self.svc.target = None
        with self.assertRaises(bridge.Refused) as e:
            self.upload(False)
        self.assertEqual(e.exception.status, 503)


